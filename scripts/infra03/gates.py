def _now() -> str:
    return datetime.now(tz=UTC).isoformat(timespec="seconds")


class GateRunner:
    def __init__(self, root: Path, artifact_zip: Path, instance_base: Path | None = None) -> None:
        self.root = root
        self.artifact_zip = artifact_zip
        self.instance_base = instance_base or Path("/tmp/epd2-infra03-gates")
        self.evidence_dir = root / EVIDENCE_DIR
        self.evidence_dir.mkdir(parents=True, exist_ok=True)
        self.gates: dict[str, dict[str, Any]] = {}
        self.target: dict[str, str] = {}

    # -- plumbing ----------------------------------------------------------

    def _git(self, *args: str) -> str:
        return subprocess.run(
            ["git", "-C", str(self.root), *args],
            capture_output=True,
            text=True,
            timeout=300,
            check=True,
        ).stdout.strip()

    def _record(self, gate_id: str, state: str, detail: str, evidence: str | None = None) -> None:
        self.gates[gate_id] = {
            "gate": gate_id,
            "title": GATES[gate_id],
            "state": state,
            "detail": detail,
            "evidence": evidence,
        }
        print(f"[{state:>7}] {gate_id} {GATES[gate_id]}: {detail[:100]}", flush=True)

    def _emit(self, name: str, payload: dict[str, Any]) -> str:
        document = {"schema": f"epd2.infra03.{name.replace('.json', '')}/1", "generated_at": _now()}
        document.update(payload)
        target = self.evidence_dir / name
        sealed = seal_document(document)
        target.write_text(json.dumps(sealed, indent=1, sort_keys=True) + "\n", encoding="utf-8")
        return name

    def _from_findings(
        self, gate_id: str, findings: list[str], detail_ok: str, evidence: str | None = None
    ) -> None:
        if findings:
            self._record(
                gate_id, "FAIL", f"{len(findings)} finding(s): {findings[0][:80]}", evidence
            )
        else:
            self._record(gate_id, "PASS", detail_ok, evidence)

    # -- governance / static gates ----------------------------------------

    def _gate_bootstrap(self) -> None:
        self._git("fetch", "--no-tags", "origin", "main")
        commit = self._git("rev-parse", "origin/main")
        tree = self._git("rev-parse", "origin/main^{tree}")
        timestamp = self._git("show", "-s", "--format=%cI", "origin/main")
        self.target = {"commit": commit, "tree": tree, "commit_timestamp": timestamp}
        required = [
            "docs/roadmap/EPD2_PROJECT_ENTRYPOINT.md",
            "docs/roadmap/EPD2_PROGRAM_CONTROL_REGISTER.md",
            "docs/roadmap/EPD2_MASTER_FUTURE_IMPLEMENTATION_REGISTER.md",
            "docs/infra/INFRA-01/INFRA01_C3_ACCEPTANCE_RECORD.json",
            "docs/infra/INFRA-02/INFRA02_ACCEPTANCE_RECORD.json",
            "docs/ops/OPS-01/OPS01_C2_ACCEPTANCE_RECORD.json",
        ]
        controlling: dict[str, str] = {}
        missing: list[str] = []
        for path in required:
            try:
                data = subprocess.run(
                    ["git", "-C", str(self.root), "show", f"origin/main:{path}"],
                    capture_output=True,
                    timeout=120,
                    check=True,
                ).stdout
                controlling[path] = sha256_bytes(data)
            except subprocess.CalledProcessError:
                missing.append(path)
        head_commit = self._git("rev-parse", "HEAD")
        head_tree = self._git("rev-parse", "HEAD^{tree}")
        dirty = self._git("status", "--porcelain")
        api_inventory = self._api_dependency_inventory()
        evidence = self._emit(
            "baseline_identity.json",
            {
                "note": (
                    "G01/G02/G04: live canonical target read at gate-run start; the "
                    "candidate branch identity; and the accepted API dependency "
                    "inventory. Canonical main is a governance authority overlay — the "
                    "source predecessor is the exact accepted INFRA-02 candidate "
                    "(see predecessor_identity.json)."
                ),
                "target_authority": {
                    "repository": "nepogoda1970-epd2/epd2-civic-os",
                    "branch": "main",
                    **self.target,
                    "controlling_files_sha256": controlling,
                    "missing_controlling_files": missing,
                },
                "candidate_branch": {
                    "commit": head_commit,
                    "tree": head_tree,
                    "dirty_paths": [line[3:] for line in dirty.splitlines() if line.strip()],
                },
                "api_dependency_inventory": api_inventory,
                "read_at": _now(),
            },
        )
        if missing:
            self._record("G01", "FAIL", f"controlling files missing on main: {missing}", evidence)
        else:
            self._record("G01", "PASS", f"target main@{commit[:12]} read live", evidence)
        self._record("G02", "PASS", f"branch HEAD {head_commit[:12]} recorded", evidence)
        stale_api = [
            entry for entry in api_inventory["accepted_stages"] if not entry.get("accepted")
        ]
        if stale_api:
            self._record("G04", "FAIL", f"unaccepted API dependency: {stale_api}", evidence)
        else:
            self._record(
                "G04",
                "PASS",
                "API-01..05 accepted records inventoried; preview shells consume no "
                "unaccepted API runtime",
                evidence,
            )

    def _api_dependency_inventory(self) -> dict[str, Any]:
        stages = {
            "API-02": "docs/api/API-02/API02_C13_ACCEPTANCE_RECORD.json",
            "API-03": "docs/api/API-03/API03_C5_ACCEPTANCE_RECORD.json",
            "API-04": "docs/api/API-04/API04_C1_ACCEPTANCE_RECORD.json",
            "API-05": "docs/api/API-05/API05_C1_ACCEPTANCE_RECORD.json",
        }
        inventory: list[dict[str, Any]] = []
        # API-01 predates per-stage acceptance-record JSON files: its
        # acceptance is recorded canonically in the Program Control Register
        # transition section and reconciliation documents.
        pcr_bytes = subprocess.run(
            [
                "git",
                "-C",
                str(self.root),
                "show",
                "origin/main:docs/roadmap/EPD2_PROGRAM_CONTROL_REGISTER.md",
            ],
            capture_output=True,
            timeout=120,
            check=True,
        ).stdout
        pcr_text = pcr_bytes.decode("utf-8", errors="replace")
        inventory.append(
            {
                "stage": "API-01",
                "record": "docs/roadmap/EPD2_PROGRAM_CONTROL_REGISTER.md "
                "(API-01 authoritative transition; reconciliations under docs/api/API-01/)",
                "decision": "ACCEPTED / CLOSED"
                if "API-01 = ACCEPTED / CLOSED" in pcr_text
                else "NOT FOUND",
                "accepted": "API-01 = ACCEPTED / CLOSED" in pcr_text,
                "record_sha256": sha256_bytes(pcr_bytes),
            }
        )
        for stage, path in stages.items():
            entry: dict[str, Any] = {"stage": stage, "record": path}
            try:
                data = subprocess.run(
                    ["git", "-C", str(self.root), "show", f"origin/main:{path}"],
                    capture_output=True,
                    timeout=120,
                    check=True,
                ).stdout
                record = json.loads(data)
                decision = (
                    str(record.get("decision", "")).upper().replace("_", " ").replace("/", " ")
                )
                entry["decision"] = str(record.get("decision"))
                entry["accepted"] = "ACCEPTED" in decision
                entry["record_sha256"] = sha256_bytes(data)
            except (subprocess.CalledProcessError, json.JSONDecodeError) as error:
                entry["accepted"] = False
                entry["error"] = str(error)[:120]
            inventory.append(entry)
        return {
            "accepted_stages": inventory,
            "runtime_consumption": (
                "the preview runtime shells implement infrastructure semantics only; "
                "no unaccepted API business runtime is consumed. Accepted API stages "
                "are the governed future occupants of the declared topology slots; "
                "API-06 is accepted/closed on live governance; no API-06 business runtime is bundled into INFRA-03."
            ),
        }

    def _gate_predecessor(self) -> None:
        record_bytes = subprocess.run(
            [
                "git",
                "-C",
                str(self.root),
                "show",
                "origin/main:docs/infra/INFRA-02/INFRA02_ACCEPTANCE_RECORD.json",
            ],
            capture_output=True,
            timeout=120,
            check=True,
        ).stdout
        record = json.loads(record_bytes)
        record_findings = [f.describe() for f in verify_predecessor_record(record)]
        staged_findings = [f.describe() for f in verify_approved_artifact(self.artifact_zip)]
        evidence = self._emit(
            "predecessor_identity.json",
            {
                "predecessor": dict(PREDECESSOR),
                "acceptance_record_sha256": sha256_bytes(record_bytes),
                "acceptance_record_source": "origin/main (live)",
                "record_verification_findings": record_findings,
                "staged_artifact": {
                    "path": str(self.artifact_zip),
                    "sha256": sha256_file(self.artifact_zip)
                    if self.artifact_zip.is_file()
                    else "ABSENT",
                    "verification_findings": staged_findings,
                },
            },
        )
        self._from_findings(
            "G03",
            record_findings + staged_findings,
            f"exact accepted INFRA-02 {str(PREDECESSOR['zip_sha256'])[:12]} verified from "
            "record and staged bytes",
            evidence,
        )

    def _gate_catalog_topology(self) -> tuple[dict[str, Any], bool]:
        catalog_findings = [f.describe() for f in validate_catalog(self.root)]
        evidence = self._emit(
            "environment_catalog_result.json",
            {
                "catalog_file": str(CATALOG_FILE),
                "catalog_sha256": sha256_file(self.root / CATALOG_FILE),
                "findings": catalog_findings,
                "environments": ["local_dev", "ci_runtime", "preview"],
            },
        )
        self._from_findings("G05", catalog_findings, "catalog complete and governed", evidence)

        topology = load_topology(self.root)
        manifest_text = (self.root / TOPOLOGY_FILE).read_text(encoding="utf-8")
        topology_findings = [f.describe() for f in validate_topology(topology, manifest_text)]
        flow_findings = [f.describe() for f in validate_flow_inventory(self.root, topology)]
        evidence = self._emit(
            "runtime_topology_result.json",
            {
                "topology_file": str(TOPOLOGY_FILE),
                "topology_sha256": sha256_file(self.root / TOPOLOGY_FILE),
                "services": sorted(topology.get("services", {})),
                "network_segments": sorted(topology.get("network_segments", {})),
                "findings": topology_findings,
            },
        )
        self._from_findings(
            "G06", topology_findings + flow_findings, "topology complete, flows declared", evidence
        )

        # G09: the declaration is reproducibly loadable and secret-free.
        reparsed_equal = load_topology(self.root) == topology
        manifest_secret_findings = [
            f.describe() for f in scan_manifest_for_secrets(manifest_text, str(TOPOLOGY_FILE))
        ]
        g09_findings = manifest_secret_findings + (
            []
            if reparsed_equal
            else [f"{codes.TOPOLOGY_INCOMPLETE}: topology: non-deterministic parse"]
        )
        self._from_findings(
            "G09",
            g09_findings,
            "versioned, lintable, deterministic, secret-free declaration",
            "runtime_topology_result.json",
        )
        return topology, not (catalog_findings or topology_findings or flow_findings)

